#!/bin/sh
# Compiles the native renderer's own shaders into SPIR-V headers, checked in
# so the build doesn't need a GLSL compiler. Run from this directory after
# changing a shader.
set -e
compile() {  # name, source, extra arguments
  out="../generated_$1.h"
  shift
  {
    echo "// Generated by src/native/glsl/compile.sh from $1; don't edit."
    echo "#pragma once"
    echo "#include <cstdint>"
    printf 'inline constexpr uint32_t k_%s[] = ' "$(basename "$out" .h | sed 's/^generated_//')"
    glslc -O --target-env=vulkan1.3 -mfmt=c -o - "$@"
    echo ";"
  } > "$out"
}
compile resolve_vert resolve.vert
compile resolve_frag resolve.frag
compile resolve_ms_frag resolve.frag -DMULTISAMPLE
compile id_frag id.frag
compile gamma_comp gamma.comp
compile movie_frag movie.frag
