#!/bin/sh
# Compiles the native renderer's own shaders into SPIR-V headers, and writes
# them as HLSL (Shader Model 5, through SPIRV-Cross) for the D3D11 backend
# (docs/d3d11-backend.md, "Shaders for D3D11"); checked in so the build
# doesn't need a shader compiler. Run from this directory after changing a
# shader. Needs glslc and spirv-cross (tools/build_spirv_cross.sh builds it
# into out/tools; $SPIRV_CROSS or the PATH otherwise). --check-hlsl also
# compiles the HLSL with D3DCompile under Wine (tools/hlsl_check).
set -e
SPIRV_CROSS=${SPIRV_CROSS:-../../../out/tools/spirv-cross/spirv-cross}
[ -x "$SPIRV_CROSS" ] || SPIRV_CROSS=spirv-cross
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
CHECKS=
compile() {  # name, source, extra arguments
  out="../generated_$1.h"
  name=$1
  shift
  [ "$HLSL_ONLY" ] || {
    echo "// Generated by src/native/glsl/compile.sh from $1; don't edit."
    echo "#pragma once"
    echo "#include <cstdint>"
    printf 'inline constexpr uint32_t k_%s[] = ' "$name"
    glslc -O --target-env=vulkan1.3 -mfmt=c -o - "$@"
    echo ";"
  } > "$out"
  # The HLSL, from SPIR-V with its names; vertex shaders with Y flipped to
  # D3D's clip space.
  case "$1" in
    *.vert) profile=vs_5_0; flip=--flip-vert-y ;;
    *.frag) profile=ps_5_0; flip= ;;
    *.comp) profile=cs_5_0; flip= ;;
  esac
  glslc --target-env=vulkan1.3 -o "$TMP/$name.spv" "$@"
  "$SPIRV_CROSS" --hlsl --shader-model 50 $flip "$TMP/$name.spv" --output "$TMP/$name.hlsl"
  {
    echo "// Generated by src/native/glsl/compile.sh from $1 (HLSL for the D3D11"
    echo "// backend, through SPIRV-Cross); don't edit."
    echo "#pragma once"
    printf 'inline constexpr char k_hlsl_%s[] = R"hlsl(' "$name"
    cat "$TMP/$name.hlsl"
    echo ')hlsl";'
  } > "../generated_${name}_hlsl.h"
  CHECKS="$CHECKS $profile:$TMP/$name.hlsl"
}
compile resolve_vert resolve.vert
compile resolve_frag resolve.frag
compile resolve_ms_frag resolve.frag -DMULTISAMPLE
compile id_frag id.frag
compile gamma_comp gamma.comp
compile movie_frag movie.frag
# The D3D11 backend's alone (what Vulkan does with its own commands): HLSL only.
HLSL_ONLY=1 compile blit_frag blit.frag
HLSL_ONLY=1 compile swizzle_frag swizzle.frag
if [ "$1" = --check-hlsl ]; then
  WINEPREFIX=${WINEPREFIX:-$PWD/../../../out/wineprefix} WINEDEBUG=-all \
    WINEDLLOVERRIDES="mscoree,mshtml=" wine ../../../out/tools/hlsl_check.exe $CHECKS
fi
