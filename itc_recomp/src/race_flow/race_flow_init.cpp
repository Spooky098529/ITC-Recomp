// RaceFlow::Init (sub_82160AE0, docs/functions/race-flow.md) as plain C++:
// the state (+9604) = 1, the flags (+9608) = 0, the players (+9612, +9616)
// 0 and 1, or both 0 when the race data's kind (+0xA3AF0) is 6, then the
// race flow's 53 transitions added (StateMachine::Add). As
// RaceHudMachine::Init (src/race_hud_machine/race_hud_machine_init.cpp),
// the original builds each transition's functor and key in its own stack
// frame (3,600 bytes) and copies the functor's six storage words from a
// temporary there, three of which it never writes (five for the
// transitions without a handler, vtable 0x820069BC): the transitions keep
// whatever the stack held (B7 changes no behavior). So the stores and
// copies are replayed in the original's frame, in its order (the table
// below, decoded from the generated code by a script that followed its
// registers: constants, the machine's offsets and the frame's), and the
// transitions get the same words. The frame's back chain and saved
// registers aren't written.

