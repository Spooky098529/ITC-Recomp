// plain C++: the race overlays' state machine's 33 transitions added
// (StateMachine::Add). The original builds each transition's functor and
// key in its own stack frame (2,272 bytes) and copies the functor's six
// storage words from a temporary there, three of which it never writes: the
// transitions keep whatever the stack held (nothing reads them: the
// delegates' Invoke reads only +4 and +8). So the stores and copies are
// replayed in the original's frame, in its order (the table below, read
// from the generated code), and the transitions get the same words. The
// frame's back chain and saved registers aren't written.

