constexpr uint32_t kFrameBytes = 17888;  // stwu r1,-17888(r1)

uint32_t L32(uint8_t* base, uint32_t address) { return guest::LoadU32(base, address); }
void S32(uint8_t* base, uint32_t address, uint32_t value) {
  guest::StoreU32(base, address, value);
}
// lfs: the word as a float, widened.
double ToDouble(uint32_t word) { return double(std::bit_cast<float>(word)); }
// stfs: rounded to a float.
void SF(uint8_t* base, uint32_t address, double value) {
  guest::StoreU32(base, address, std::bit_cast<uint32_t>(float(value)));
}

