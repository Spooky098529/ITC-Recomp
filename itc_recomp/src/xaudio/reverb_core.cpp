// spills, and its buffers are the stages' inputs and outputs): the scalar
// unit's float work with flush to zero off and the vector unit's with it on
// (ppc_float.h); a float stored straight from its load keeps its bits, as the
// translated code's folded lfs/stfs pairs do. The stack frame is the
// original's (17,888 bytes below the caller's stack pointer), and every word
// the original writes there is written, except its register saves. Built with
// strict floating point and no contraction (CMakeLists.txt).

