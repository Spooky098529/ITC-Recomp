// RaceStates::Init (sub_82169920, docs/functions/race-states.md) as plain
// C++: RaceProgress::Create, +9624 = [0x826D82E8], RaceProgress::Reset of
// it, +9604 = 1, then the race's states' 87 transitions added
// (StateMachine::Add). As RaceWorld::Init (src/race_world/race_world_init.cpp),
// the original builds each transition's functor and key in its own stack
// frame (5,824 bytes) and copies the functor's six storage words from a
// temporary there, three of which it never writes (five for the transitions
// without a handler, vtable 0x820069BC): the transitions keep whatever the
// stack held. So the stores and copies are replayed in the original's
// frame, in its order (the table below, decoded from the generated code by
// a script that followed its registers), and the transitions get the same
// words. The frame's back chain and saved registers aren't written.

