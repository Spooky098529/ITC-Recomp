// RaceHudMachine::Init (sub_8216E6E8, docs/functions/race-hud-machine.md)
// as plain C++: the state (+9604) = 0, then the race HUD machine's 65
// transitions added (StateMachine::Add). As RaceSceneMachine::Init
// (src/race_scene/race_scene_init.cpp), the original builds each
// transition's functor and key in its own stack frame (4,400 bytes) and
// copies the functor's six storage words from a temporary there, three of
// which it never writes (five for the transitions without a handler, vtable
// 0x820069BC): the transitions keep whatever the stack held. So the stores
// and copies are replayed in the original's frame, in its order (the table
// below, decoded from the generated code by a script that followed its
// registers: constants, the machine's offsets and the frame's), and the
// transitions get the same words. The frame's back chain and saved
// registers aren't written.

