"""Writes itc_recomp/src/image/image_rdata.cpp and image_data.cpp: the data
the game reads from its image (default.xex's .rdata and .data sections, its
constants, strings, tables and initialized globals), compiled in so
default.xex is no longer read (docs/e5-native.md, step 8). Run on the
developer's machine with the player's default.xex (the US release, checked
by its SHA-1):

  python3 -I itc_recomp/tools/image_data.py <default.xex>

Needs the `cryptography` package (AES). The code sections (.text, the
.embsec_ sections), the headers, .pdata, .idata, .XBLD and .reloc aren't
written: the code is ours (src/lifted/ and the hand ports), and nothing
reads the rest. Runs of zeros are left out (the image is zeroed first).
The words are the guest's: big-endian values, stored with guest::StoreU32.
"""
import hashlib
import os
import struct
import sys

from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes

SHA1 = '32932de0c037ab28192dfbed314ac5efcf400f16'
RETAIL_KEY = bytes.fromhex('20B185A59D28FDC340583FBB0896BF91')
LOAD_ADDRESS = 0x82000000
# The sections written: (name, first address, end address).
SECTIONS = [
    ('rdata', 0x82000600, 0x82077400),
    ('data', 0x82600000, 0x82978400),
]
GAP = 64  # zero bytes that end a chunk
OUT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'image')


def load_image(path):
    f = open(path, 'rb').read()
    if hashlib.sha1(f).hexdigest() != SHA1:
        sys.exit(f"{path}: not the US release's default.xex (its SHA-1 differs)")
    be = lambda at: struct.unpack('>I', f[at:at + 4])[0]
    data_offset, security, count = be(8), be(16), be(20)
    file_format = load_address = None
    for i in range(count):
        key, value = be(24 + 8 * i), be(28 + 8 * i)
        if key == 0x3FF:
            file_format = value
        elif key == 0x10201:
            load_address = value
    assert load_address == LOAD_ADDRESS and file_format is not None
    image_size = be(security + 4)
    decrypt = Cipher(algorithms.AES(RETAIL_KEY), modes.ECB()).decryptor()
    key = decrypt.update(f[security + 0x150:security + 0x160])
    size = (len(f) - data_offset) & ~15
    decrypt = Cipher(algorithms.AES(key), modes.CBC(bytes(16))).decryptor()
    data = decrypt.update(f[data_offset:data_offset + size])
    image = bytearray(image_size)
    src = dst = 0
    at = file_format + 8
    while at + 8 <= file_format + be(file_format):
        n, zeros = be(at), be(at + 4)
        image[dst:dst + n] = data[src:src + n]
        src += n
        dst += n + zeros
        at += 8
    return image


def chunks(image, first, end):
    """(address, bytes) spans of [first, end) holding nonzero bytes, 4-aligned."""
    out = []
    at = first
    while at < end:
        while at < end and image[at - LOAD_ADDRESS] == 0:
            at += 1
        if at >= end:
            break
        start = at & ~3
        zeros = 0
        last = at
        while at < end and zeros < GAP:
            if image[at - LOAD_ADDRESS]:
                zeros = 0
                last = at
            else:
                zeros += 1
            at += 1
        stop = (last + 4) & ~3
        out.append((start, bytes(image[start - LOAD_ADDRESS:stop - LOAD_ADDRESS])))
        at = stop
    return out


def write(name, first, end, image):
    spans = chunks(image, first, end)
    lines = [
        f'// Generated by itc_recomp/tools/image_data.py from default.xex: its .{name}',
        f'// section ({first:08X} to {end:08X}), the runs holding nonzero bytes, as',
        '// big-endian words. See src/image/image.h.',
        '',
        '#include "image/image.h"',
        '',
        '#include <iterator>',
        '',
        'namespace image {',
        '',
        'namespace {',
        '',
    ]
    for address, data in spans:
        words = struct.unpack(f'>{len(data) // 4}I', data)
        lines.append(f'constexpr uint32_t k{address:08X}[] = {{')
        for i in range(0, len(words), 8):
            lines.append('    ' + ', '.join(f'0x{w:08X}' for w in words[i:i + 8]) + ',')
        lines.append('};')
    lines += ['', '}  // namespace', '']
    lines.append(f'extern const Chunk k{name.capitalize()}Chunks[] = {{')
    for address, _ in spans:
        lines.append(f'    {{0x{address:08X}, uint32_t(std::size(k{address:08X})), k{address:08X}}},')
    lines.append('};')
    lines.append(f'extern const size_t k{name.capitalize()}ChunkCount = {len(spans)};')
    lines += ['', '}  // namespace image', '']
    path = os.path.join(OUT_DIR, f'image_{name}.cpp')
    open(path, 'w').write('\n'.join(lines))
    print(f'{os.path.relpath(path)}: {len(spans)} chunks, '
          f'{sum(len(d) for _, d in spans):,} bytes')


def main():
    image = load_image(sys.argv[1])
    for name, first, end in SECTIONS:
        write(name, first, end, image)


main()
