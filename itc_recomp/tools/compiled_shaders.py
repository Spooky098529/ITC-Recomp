"""Writes itc_recomp/src/graphics/compiled_shaders.h: the shaders the game's
HLSL compiler (D3DXCompileShader, sub_822B8F10) made at boot from source in
the image, plugged in by --use_hardcoded_shaders (src/hooks/shader_compiles.cpp).

  python3 -I itc_recomp/tools/compiled_shaders.py <dump dir> <image>

<dump dir> holds shader_<source>_<profile>.bin, as --dump_shader_compiles
writes them (src/debug/shader_compile_dump.cpp); <image> is the dumped
executable image (--dump_image), for each source's length (the callers pass
the string's length).
"""
import os
import re
import sys

dump_dir, image_path = sys.argv[1], sys.argv[2]
BASE = 0x82000000
image = open(image_path, 'rb').read()

shaders = []
for name in sorted(os.listdir(dump_dir)):
    m = re.fullmatch(r'shader_([0-9A-F]{8})_([vp]s_\d_\d)\.bin', name)
    if not m:
        continue
    source, profile = int(m.group(1), 16), m.group(2)
    offset = source - BASE
    length = image.index(b'\0', offset) - offset
    data = open(os.path.join(dump_dir, name), 'rb').read()
    shaders.append((source, length, profile, data))

out = []
out.append('// Generated by itc_recomp/tools/compiled_shaders.py: the shaders the game\'s')
out.append('// HLSL compiler (sub_822B8F10) makes at boot from source in the image, as it')
out.append('// made them (big-endian, as in guest memory). See --use_hardcoded_shaders.')
out.append('')
out.append('#pragma once')
out.append('')
out.append('#include <cstdint>')
out.append('')
out.append('namespace graphics::compiled_shaders {')
out.append('')
for source, length, profile, data in shaders:
    out.append(f'inline constexpr uint8_t k{source:08X}[{len(data)}] = {{')
    for i in range(0, len(data), 16):
        out.append('    ' + ', '.join(f'0x{b:02X}' for b in data[i:i + 16]) + ',')
    out.append('};')
    out.append('')
out.append('struct Entry {')
out.append('  uint32_t source;  // the HLSL\'s address in the image')
out.append('  uint32_t length;  // its length, as the callers pass it')
out.append('  const char* profile;')
out.append('  const uint8_t* data;')
out.append('  uint32_t size;')
out.append('};')
out.append('')
out.append('inline constexpr Entry kShaders[] = {')
for source, length, profile, data in shaders:
    out.append(f'    {{0x{source:08X}, {length}, "{profile}", k{source:08X}, {len(data)}}},')
out.append('};')
out.append('')
out.append('}  // namespace graphics::compiled_shaders')
out.append('')

path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'graphics',
                    'compiled_shaders.h')
with open(path, 'w') as f:
    f.write('\n'.join(out))
print(f'{len(shaders)} shaders written to {os.path.normpath(path)}')
