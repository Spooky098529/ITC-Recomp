#!/usr/bin/env python3
"""Writes the renderer's table of shaders (src/native/game_shader_ports.h)
from a shaders.json, and merges another port_all.py run into it first.

ITC-Recomp's: the ports came from SBX-Recomp's run over its files (its
shaders.json, in src/native/glsl/game), and our own runs over the shader
files the game loads here (--dump_shader_files) add the shaders that run
didn't find (docs/pc-renderer.md, step 2).

  table_from_json.py <glsl/game folder> <table.h> [<other port_all --out folder> ...]

An other folder's ports (its .vert and .frag files) not in the first
folder's shaders.json are copied in, and their entries added to it."""
import json, os, shutil, sys

def title(e):
    where = e["found_in"][0].replace("\\", "/")
    return (e["part_id"] + " " if e.get("part_id") else "") + where

def entry_lines(e):
    stage = "kVertex" if e["stage"] == "vs" else "kPixel"
    name = "%s_%s" % (e["stage"], e["hash"])
    lines = ['  {ShaderStage::%s, 0x%sull, %d, k_game_%s, std::size(k_game_%s), "%s",' % (
        stage, e["lookup_hash"], e["microcode_words"], name, name, title(e))]
    fetches = [str(f["instruction"]) for f in e["vertex_fetches"]]
    lines.append("   {{%s}}, %d," % (", ".join(fetches), len(fetches)))
    textures = ["{%d, %s}" % (t["fetch_constant"], "true" if t["view"] == "cube" else "false")
                for t in e["textures"] if not t.get("signed")]
    lines.append("   {{%s}}, %d," % (", ".join(textures), len(textures)))
    samplers = ["{%d, %d, %d, %d, %d}" % (s["fetch_constant"], s["mag"], s["min"], s["mip"], s["aniso"])
                for s in e["samplers"]]
    lines.append("   {{%s}}, %d," % (", ".join(samplers), len(samplers)))
    # The float constants read (all 256 when addressed relative to the loop
    # index), the interpolators written (vertex) or read (pixel: as many as
    # its registers, up to 16), and the color targets written.
    floats = [0, 0, 0, 0]
    for r in (range(256) if e["relative_constants"] else e["float_constants"]):
        floats[r >> 6] |= 1 << (r & 63)
    interpolators = sum(1 << i for i in e["interpolators"] if i < 16)
    targets = sum(1 << t for t in e["color_targets"])
    lines.append("   {{%s}}, 0x%X, 0x%X}," % (", ".join("0x%016Xull" % f for f in floats),
                                            interpolators, targets))
    return lines

def main():
    folder, table, others = sys.argv[1], sys.argv[2], sys.argv[3:]
    path = os.path.join(folder, "shaders.json")
    catalog = json.load(open(path))
    have = {e["hash"] for e in catalog}
    added = 0
    for other in others:
        for e in json.load(open(os.path.join(other, "shaders.json"))):
            if e["hash"] in have or not e.get("port"):
                continue
            shutil.copy(os.path.join(other, e["port"]), os.path.join(folder, e["port"]))
            catalog.append(e)
            have.add(e["hash"])
            added += 1
    json.dump(catalog, open(path, "w", newline="\n"), indent=1)
    L = ["// Generated by tools/shader_port/table_from_json.py from glsl/game/shaders.json;",
         "// don't edit. The game's shaders written as GLSL (src/native/glsl), for",
         "// ShaderCache (shaders.cpp): see docs/shaders.md.",
         "#pragma once", "", "#include <iterator>", "", '#include "generated_game_shaders.h"',
         '#include "shader_ports.h"', "", "namespace native {", "",
         "inline constexpr GamePort kGamePorts[] = {"]
    for e in sorted((e for e in catalog if e.get("port")), key=lambda e: (e["stage"] == "vs", e["hash"])):
        L += entry_lines(e)
    L += ["};", "", "}  // namespace native", ""]
    open(table, "w", newline="\n").write("\n".join(L))
    print("%d shaders in the table, %d added" % (sum(1 for e in catalog if e.get("port")), added))

if __name__ == "__main__":
    main()
